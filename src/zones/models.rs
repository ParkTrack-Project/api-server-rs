use sea_query::Iden;
#[derive(Iden)]
pub enum ParkingZones {
    Table,
    ParkingZoneId,
    CameraId,
    ZoneType,
    Capacity,
    Occupied,
    FreeCount,
    Confidence,
    ConfidenceLevel,
    Pay,
    Geometry,
    ImagePolygon,
    PartnerId,
    CreatedByUserId,
    IsActive,
    LocationType,
    IsPrivate,
    IsAccessible,
    OccupancyUpdatedAt,
    CreatedAt,
    UpdatedAt,
    CentroidLatitude,
    CentroidLongitude,
}
#[derive(Debug, sqlx::FromRow)]
pub struct ZoneRow {
    pub parking_zone_id: i32,
    pub camera_id: i32,
    pub zone_type: String,
    pub capacity: i32,
    pub occupied: i32,
    pub free_count: i32,
    pub confidence: Option<f64>,
    pub confidence_level: Option<String>,
    pub pay: i32,
    pub geometry: serde_json::Value,
    pub image_polygon: serde_json::Value,
    pub partner_id: Option<i32>,
    pub created_by_user_id: Option<i32>,
    pub is_active: Option<bool>,
    pub location_type: Option<String>,
    pub is_private: Option<bool>,
    pub is_accessible: Option<bool>,
    pub occupancy_updated_at: Option<chrono::DateTime<chrono::Utc>>,
    pub created_at: Option<chrono::DateTime<chrono::Utc>>,
    pub updated_at: Option<chrono::DateTime<chrono::Utc>>,
    pub centroid_latitude: Option<f64>,
    pub centroid_longitude: Option<f64>,
}
